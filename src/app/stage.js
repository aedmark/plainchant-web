function buildBridgeScript(designMode, initialSelectedId, forcedState) {
    if (!designMode) return buildLiveBridgeScript();
    return [
        '(function() {',
        '  var selectedId = ' + JSON.stringify(initialSelectedId || null) + ';',
        '  var forced = ' + JSON.stringify(forcedState || '') + ';',
        '  var FORCE = { hover: ["hover"], active: ["active", "hover"], focus: ["focus", "focus-within"], "focus-visible": ["focus-visible", "focus", "focus-within"], "focus-within": ["focus-within"] };',
        '  var editingEl = null, dragState = null, suppressNextClick = false;',
        '  var marginBox = document.createElement("div"); marginBox.id = "pc-margin-box";',
        '  var paddingBox = document.createElement("div"); paddingBox.id = "pc-padding-box";',
        '  var badge = document.createElement("div"); badge.id = "pc-stage-badge";',
        '  document.body.append(marginBox, paddingBox, badge);',
        '  function labelOf(el) {',
        '    if (!el || !el.tagName) return "";',
        '    var s = el.tagName.toLowerCase();',
        '    if (el.id) s += "#" + el.id;',
        '    if (el.className && typeof el.className === "string") {',
        '      var c = el.className.trim().split(/\\s+/).filter(Boolean).slice(0, 2);',
        '      if (c.length) s += "." + c.join(".");',
        '    }',
        '    return s;',
        '  }',
        '  function readComputed(el) {',
        '    if (!el || el.nodeType !== 1) return null;',
        '    var cs = window.getComputedStyle(el), r = el.getBoundingClientRect();',
        '    return {',
        '      display: cs.display, padding: cs.padding, margin: cs.margin, gap: cs.gap,',
        '      width: Math.round(r.width) + "px", height: Math.round(r.height) + "px", maxWidth: cs.maxWidth,',
        '      fontSize: cs.fontSize, textAlign: cs.textAlign, borderRadius: cs.borderRadius,',
        '      color: cs.color, backgroundColor: cs.backgroundColor',
        '    };',
        '  }',
        '  function updateBoxOverlay(el) {',
        '    if (!el || el === document.body || el === document.documentElement) {',
        '      marginBox.style.display = "none";',
        '      paddingBox.style.display = "none";',
        '      return;',
        '    }',
        '    var r = el.getBoundingClientRect();',
        '    var cs = window.getComputedStyle(el);',
        '    var mt = Math.max(0, parseFloat(cs.marginTop) || 0);',
        '    var mr = Math.max(0, parseFloat(cs.marginRight) || 0);',
        '    var mb = Math.max(0, parseFloat(cs.marginBottom) || 0);',
        '    var ml = Math.max(0, parseFloat(cs.marginLeft) || 0);',
        '    var pt = Math.max(0, parseFloat(cs.paddingTop) || 0);',
        '    var pr = Math.max(0, parseFloat(cs.paddingRight) || 0);',
        '    var pb = Math.max(0, parseFloat(cs.paddingBottom) || 0);',
        '    var pl = Math.max(0, parseFloat(cs.paddingLeft) || 0);',
        '    marginBox.style.display = "block";',
        '    marginBox.style.top = (r.top - mt) + "px";',
        '    marginBox.style.left = (r.left - ml) + "px";',
        '    marginBox.style.width = (r.width + ml + mr) + "px";',
        '    marginBox.style.height = (r.height + mt + mb) + "px";',
        '    marginBox.style.borderWidth = mt + "px " + mr + "px " + mb + "px " + ml + "px";',
        '    paddingBox.style.display = "block";',
        '    paddingBox.style.top = r.top + "px";',
        '    paddingBox.style.left = r.left + "px";',
        '    paddingBox.style.width = r.width + "px";',
        '    paddingBox.style.height = r.height + "px";',
        '    paddingBox.style.borderWidth = pt + "px " + pr + "px " + pb + "px " + pl + "px";',
        '  }',
        '  var NON_TEXT_TAGS = { IMG:1, INPUT:1, TEXTAREA:1, SELECT:1, IFRAME:1, VIDEO:1, AUDIO:1, CANVAS:1, SVG:1, HR:1, BR:1, UL:1, OL:1, TABLE:1, TR:1, FORM:1, NAV:1, HEADER:1, FOOTER:1, MAIN:1, SECTION:1, ARTICLE:1 };',
        '  function isTextEditable(el) {',
        '    if (!el || el.nodeType !== 1 || el === document.body || el === document.documentElement) return false;',
        '    if (NON_TEXT_TAGS[el.tagName]) return false;',
        '    return el.children.length === 0;',
        '  }',
        '  function placeCaretAtPoint(el, x, y) {',
        '    try {',
        '      var sel = window.getSelection();',
        '      if (!sel) return;',
        '      var range = null;',
        '      if (document.caretRangeFromPoint) {',
        '        range = document.caretRangeFromPoint(x, y);',
        '      } else if (document.caretPositionFromPoint) {',
        '        var pos = document.caretPositionFromPoint(x, y);',
        '        if (pos && pos.offsetNode) {',
        '          range = document.createRange();',
        '          range.setStart(pos.offsetNode, pos.offset);',
        '          range.collapse(true);',
        '        }',
        '      }',
        '      if (range && el.contains(range.startContainer)) {',
        '        sel.removeAllRanges();',
        '        sel.addRange(range);',
        '      }',
        '    } catch (err) {}',
        '  }',
        '  function startInlineEdit(el, x, y) {',
        '    if (!el || el === document.body || el === document.documentElement) return;',
        '    if (editingEl && editingEl !== el) finishInlineEdit(true);',
        '    if (editingEl === el) return;',
        '    editingEl = el;',
        '    window.parent.postMessage({ type: "pc-inline-start", id: el.getAttribute("data-pc-id") }, "*");',
        '    el.setAttribute("data-pc-editing", "true");',
        '    el.setAttribute("contenteditable", "true");',
        '    el.focus({ preventScroll: true });',
        '    if (typeof x === "number" && typeof y === "number") {',
        '      placeCaretAtPoint(el, x, y);',
        '    }',
        '  }',
        '  function positionBadge(el) {',
        '    if (!el) { badge.style.display = "none"; updateBoxOverlay(null); return; }',
        '    var r = el.getBoundingClientRect();',
        '    var dims = Math.round(r.width) + "×" + Math.round(r.height);',
        '    badge.innerHTML = "";',
        '    var lbl = document.createElement("span");',
        '    lbl.style.cursor = "grab";',
        '    lbl.title = "Drag to reorder element";',
        '    lbl.textContent = "⠿ " + labelOf(el) + " · " + dims;',
        '    lbl.addEventListener("mousedown", function(ev) {',
        '      if (ev.button !== 0 || el === document.body || el === document.documentElement) return;',
        '      ev.preventDefault();',
        '      ev.stopPropagation();',
        '      if (editingEl) finishInlineEdit(true);',
        '      dragState = {',
        '        sourceId: el.getAttribute("data-pc-id"),',
        '        sourceEl: el,',
        '        startX: ev.clientX,',
        '        startY: ev.clientY,',
        '        active: false,',
        '        targetId: null,',
        '        position: null',
        '      };',
        '    });',
        '    badge.appendChild(lbl);',
        '    if (el !== document.body && el !== document.documentElement) {',
        '      var actions = [',
        '        { cmd: "pc-move-up", txt: "↑", title: "Move up" },',
        '        { cmd: "pc-move-down", txt: "↓", title: "Move down" },',
        '        { cmd: "pc-duplicate", txt: "⧉", title: "Duplicate" },',
        '        { cmd: "pc-delete", txt: "✕", title: "Delete" }',
        '      ];',
        '      if (el.tagName === "A" && el.getAttribute("href")) actions.unshift({ cmd: "pc-follow-link", txt: "Follow ↗", title: "Open the linked page (Ctrl/Cmd+Click)" });',
        '      actions.forEach(function(a) {',
        '        var btn = document.createElement("button");',
        '        btn.type = "button";',
        '        btn.className = "pc-b-act";',
        '        btn.textContent = a.txt;',
        '        btn.title = a.title;',
        '        btn.addEventListener("click", function(ev) {',
        '          ev.preventDefault();',
        '          ev.stopPropagation();',
        '          window.parent.postMessage({ type: a.cmd, id: selectedId }, "*");',
        '        });',
        '        badge.appendChild(btn);',
        '      });',
        '    }',
        '    badge.style.display = " inline-flex";',
        '    badge.style.top = Math.max(2, r.top - 24) + "px";',
        '    badge.style.left = Math.max(2, r.left) + "px";',
        '    updateBoxOverlay(el);',
        '  }',
        '  function clearDropTargets() {',
        '    var prev = document.querySelectorAll("[data-pc-drop-target]");',
        '    for (var i = 0; i < prev.length; i++) prev[i].removeAttribute("data-pc-drop-target");',
        '    var dr = document.querySelectorAll("[data-pc-dragging]");',
        '    for (var j = 0; j < dr.length; j++) dr[j].removeAttribute("data-pc-dragging");',
        '  }',
        '  function applyForce() {',
        '    var old = document.querySelectorAll("[data-pc-force]");',
        '    for (var i = 0; i < old.length; i++) old[i].removeAttribute("data-pc-force");',
        '    var el = selectedId && FORCE[forced] ? document.querySelector(\'[data-pc-id="\' + selectedId + \'"]\') : null;',
        '    if (!el) return;',
        '    el.setAttribute("data-pc-force", FORCE[forced].join(" "));',
        '    var up = forced === "focus" || forced === "focus-visible" ? "focus-within" : FORCE[forced].join(" ");',
        '    for (var p = el.parentElement; p; p = p.parentElement) p.setAttribute("data-pc-force", up);',
        '  }',
        '  function setSelect(id) {',
        '    selectedId = id;',
        '    applyForce();',
        '    var prev = document.querySelectorAll("[data-pc-selected]");',
        '    for (var i = 0; i < prev.length; i++) prev[i].removeAttribute("data-pc-selected");',
        '    if (!id) { positionBadge(null); return; }',
        '    var target = document.querySelector(\'[data-pc-id="\' + id + \'"]\');',
        '    if (target) {',
        '      target.setAttribute("data-pc-selected", "true");',
        '      positionBadge(target);',
        '      window.parent.postMessage({ type: "pc-computed", id: id, computed: readComputed(target) }, "*");',
        '    }',
        '  }',
        '  if (selectedId) setTimeout(function() { setSelect(selectedId); }, 10);',
        '  window.addEventListener("scroll", function() {',
        '    if (!selectedId) return;',
        '    var t = document.querySelector(\'[data-pc-id="\' + selectedId + \'"]\');',
        '    if (t) positionBadge(t);',
        '  }, true);',
        '  document.addEventListener("mouseover", function(e) {',
        '    if (dragState && dragState.active) return;',
        '    var el = e.target && e.target.closest ? e.target.closest("[data-pc-id]") : null;',
        '    if (!el || el === document.body) return;',
        '    el.setAttribute("data-pc-hover", "true");',
        '  });',
        '  document.addEventListener("mouseout", function(e) {',
        '    var el = e.target && e.target.closest ? e.target.closest("[data-pc-id]") : null;',
        '    if (el) el.removeAttribute("data-pc-hover");',
        '  });',
        '  document.addEventListener("dragstart", function(e) {',
        '    if (!editingEl) e.preventDefault();',
        '  }, true);',
        '  function resolveDropTarget(rawEl, sourceEl, shiftKey) {',
        '    var cur = rawEl && rawEl.closest ? rawEl.closest("[data-pc-id]") : null;',
        '    while (cur && (cur === sourceEl || sourceEl.contains(cur))) {',
        '      cur = cur.parentElement ? cur.parentElement.closest("[data-pc-id]") : null;',
        '    }',
        '    if (!cur || cur === document.body || cur === document.documentElement || cur.contains(sourceEl)) return null;',
        '    if (!shiftKey && sourceEl.parentElement) {',
        '      var probe = cur;',
        '      while (probe && probe !== document.body) {',
        '        if (probe.parentElement === sourceEl.parentElement && probe.hasAttribute("data-pc-id")) {',
        '          return probe;',
        '        }',
        '        probe = probe.parentElement;',
        '      }',
        '    }',
        '    return cur;',
        '  }',
        '  document.addEventListener("mousedown", function(e) {',
        '    window.parent.postMessage({ type: "pc-dismiss-menus" }, "*");',
        '    if (editingEl && !editingEl.contains(e.target) && !badge.contains(e.target)) {',
        '      finishInlineEdit(true);',
        '    }',
        '    if (e.button !== 0 || editingEl || badge.contains(e.target)) return;',
        '    var el = e.target && e.target.closest ? e.target.closest("[data-pc-id]") : null;',
        '    if (!el || el === document.body || el === document.documentElement) return;',
        '    var id = el.getAttribute("data-pc-id");',
        '    if (!id) return;',
        '    dragState = {',
        '      sourceId: id,',
        '      sourceEl: el,',
        '      startX: e.clientX,',
        '      startY: e.clientY,',
        '      active: false,',
        '      targetId: null,',
        '      position: null',
        '    };',
        '  }, true);',
        '  document.addEventListener("mousemove", function(e) {',
        '    if (!dragState || editingEl) return;',
        '    var dx = e.clientX - dragState.startX;',
        '    var dy = e.clientY - dragState.startY;',
        '    if (!dragState.active) {',
        '      if (Math.sqrt(dx * dx + dy * dy) < 6) return;',
        '      dragState.active = true;',
        '      dragState.sourceEl.setAttribute("data-pc-dragging", "true");',
        '      setSelect(dragState.sourceId);',
        '    }',
        '    e.preventDefault();',
        '    var target = resolveDropTarget(e.target, dragState.sourceEl, e.shiftKey);',
        '    if (!target) return;',
        '    var tid = target.getAttribute("data-pc-id");',
        '    if (!tid || tid === dragState.sourceId) return;',
        '    var prev = document.querySelectorAll("[data-pc-drop-target]");',
        '    for (var i = 0; i < prev.length; i++) prev[i].removeAttribute("data-pc-drop-target");',
        '    var r = target.getBoundingClientRect();',
        '    var sr = dragState.sourceEl.getBoundingClientRect();',
        '    var sameRow = Math.abs((r.top + r.height / 2) - (sr.top + sr.height / 2)) < Math.max(r.height, sr.height) * 0.5;',
        '    var pos = sameRow',
        '      ? ((e.clientX < r.left + r.width / 2) ? "before" : "after")',
        '      : ((e.clientY < r.top + r.height / 2) ? "before" : "after");',
        '    target.setAttribute("data-pc-drop-target", pos);',
        '    dragState.targetId = tid;',
        '    dragState.position = pos;',
        '  }, true);',
        '  window.addEventListener("mouseup", function(e) {',
        '    if (!dragState) return;',
        '    var state = dragState;',
        '    dragState = null;',
        '    clearDropTargets();',
        '    if (state.active) {',
        '      suppressNextClick = true;',
        '      if (state.targetId && state.targetId !== state.sourceId) {',
        '        window.parent.postMessage({',
        '          type: "pc-move-to",',
        '          sourceId: state.sourceId,',
        '          targetId: state.targetId,',
        '          position: state.position || "after"',
        '        }, "*");',
        '      }',
        '    }',
        '  }, true);',
        '  document.addEventListener("click", function(e) {',
        '    if (badge.contains(e.target)) return;',
        '    if (editingEl && editingEl.contains(e.target)) return;',
        '    e.preventDefault();',
        '    e.stopPropagation();',
        '    if (suppressNextClick) { suppressNextClick = false; return; }',
        '    var el = e.target && e.target.closest ? e.target.closest("[data-pc-id]") : null;',
        '    if (!el) return;',
        '    var id = el.getAttribute("data-pc-id");',
        '    var link = (e.ctrlKey || e.metaKey) && el.closest("a[href]");',
        '    if (link) { window.parent.postMessage({ type: "pc-navigate", href: link.getAttribute("href") }, "*"); return; }',
        '    setSelect(id);',
        '    window.parent.postMessage({ type: "pc-select", id: id, computed: readComputed(el) }, "*");',
        '    if (isTextEditable(el)) {',
        '      startInlineEdit(el, e.clientX, e.clientY);',
        '    } else {',
        '      window.focus();',
        '    }',
        '  }, true);',
        '  document.addEventListener("contextmenu", function(e) {',
        '    if (editingEl && editingEl.contains(e.target)) return;',
        '    e.preventDefault();',
        '    e.stopPropagation();',
        '    var el = e.target && e.target.closest ? e.target.closest("[data-pc-id]") : document.body;',
        '    var id = el ? el.getAttribute("data-pc-id") : null;',
        '    if (id) setSelect(id);',
        '    window.parent.postMessage({',
        '      type: "pc-contextmenu",',
        '      id: id,',
        '      clientX: e.clientX,',
        '      clientY: e.clientY,',
        '      computed: el ? readComputed(el) : null',
        '    }, "*");',
        '  }, true);',
        '  function finishInlineEdit(keep) {',
        '    if (!editingEl) return;',
        '    var el = editingEl;',
        '    editingEl = null;',
        '    var id = el.getAttribute("data-pc-id");',
        '    var text = el.innerText;',
        '    el.removeAttribute("contenteditable");',
        '    el.removeAttribute("data-pc-editing");',
        '    if (keep && id) {',
        '      window.parent.postMessage({ type: "pc-inline-edit", id: id, text: text }, "*");',
        '    }',
        '  }',
        '  document.addEventListener("input", function(e) {',
        '    if (!editingEl || e.target !== editingEl) return;',
        '    var id = editingEl.getAttribute("data-pc-id");',
        '    positionBadge(editingEl);',
        '    if (id) {',
        '      window.parent.postMessage({ type: "pc-inline-input", id: id, text: editingEl.innerText }, "*");',
        '    }',
        '  }, true);',
        '  document.addEventListener("dblclick", function(e) {',
        '    if (badge.contains(e.target)) return;',
        '    var el = e.target && e.target.closest ? e.target.closest("[data-pc-id]") : null;',
        '    if (!el || el === document.body) return;',
        '    e.preventDefault();',
        '    e.stopPropagation();',
        '    startInlineEdit(el, e.clientX, e.clientY);',
        '  }, true);',
        '  document.addEventListener("keydown", function(e) {',
        '    if (editingEl) {',
        '      if (e.key === "Enter" && !e.shiftKey) { e.preventDefault(); finishInlineEdit(true); }',
        '      else if (e.key === "Escape") { e.preventDefault(); finishInlineEdit(false); }',
        '    } else if ((e.ctrlKey || e.metaKey) && !e.altKey && (e.key === "z" || e.key === "Z")) {',
        '      e.preventDefault();',
        '      window.parent.postMessage({ type: e.shiftKey ? "pc-redo" : "pc-undo" }, "*");',
        '    } else if ((e.ctrlKey || e.metaKey) && !e.altKey && !e.shiftKey && (e.key === "y" || e.key === "Y")) {',
        '      e.preventDefault();',
        '      window.parent.postMessage({ type: "pc-redo" }, "*");',
        '    } else if ((e.key === "Delete" || e.key === "Backspace") && selectedId) {',
        '      e.preventDefault();',
        '      window.parent.postMessage({ type: "pc-delete", id: selectedId }, "*");',
        '    } else if (e.altKey && e.key === "ArrowUp" && selectedId) {',
        '      e.preventDefault();',
        '      window.parent.postMessage({ type: "pc-move-up", id: selectedId }, "*");',
        '    } else if (e.altKey && e.key === "ArrowDown" && selectedId) {',
        '      e.preventDefault();',
        '      window.parent.postMessage({ type: "pc-move-down", id: selectedId }, "*");',
        '    }',
        '  });',
        '  document.addEventListener("blur", function(e) {',
        '    if (editingEl && e.target === editingEl) finishInlineEdit(true);',
        '  }, true);',
        '  window.addEventListener("message", function(e) {',
        '    var d = e.data || {};',
        '    if (d.type === "pc-highlight") setSelect(d.id);',
        '    if (d.type === "pc-force-state") { forced = d.state || ""; setSelect(selectedId); }',
        '  });',
        '})();'
    ].join('\n');
}

let stageTimer = null;

function drawStageNow() {
    clearTimeout(stageTimer);
    stageTimer = null;
    const isDesign = stageMode === 'design';
    clearConsole();
    const doc = Project.assemblePreview(projectFiles, {
        ast: currentHtmlAst,
        activeHtml: activeHtmlFile,
        baseUrl: projectBaseUrl,
        assetUrls: projectAssetUrls,
        liveJs: !isDesign,
        bridgeCss: isDesign ? BRIDGE_CSS : '',
        forceStates: isDesign,
        bridgeScript: buildBridgeScript(isDesign, selectedPcId, activeCssState) + (isDesign ? buildLayoutBridgeScript() : '')
    });
    stageFrame.srcdoc = doc;
}

function scheduleStageRender(typed) {
    if (!typed) {
        drawStageNow();
        return;
    }
    clearTimeout(stageTimer);
    stageTimer = setTimeout(drawStageNow, 120);
}

function highlightOnStage(pcId) {
    if (stageFrame && stageFrame.contentWindow) {
        try {
            stageFrame.contentWindow.postMessage({ type: 'pc-highlight', id: pcId }, '*');
        } catch (e) {
        }
    }
}

window.addEventListener('message', (e) => {
    const data = e.data || {};
    if (data.type === 'pc-select' && data.id) {
        if (typeof closeContextMenu === 'function') closeContextMenu();
        if (data.computed) setStageComputedStyle(data.computed);
        selectElementById(data.id, { revealCode: true, focusEditor: false });
    } else if (data.type === 'pc-dismiss-menus') {
        if (typeof closeContextMenu === 'function') closeContextMenu();
        if (typeof setInsertMenuOpen === 'function') setInsertMenuOpen(false);
    } else if (data.type === 'pc-contextmenu') {
        if (data.computed) setStageComputedStyle(data.computed);
        if (data.id) selectElementById(data.id, { revealCode: true, focusEditor: false });
        if (typeof openContextMenuAt === 'function' && stageFrame) {
            const rect = stageFrame.getBoundingClientRect();
            openContextMenuAt(rect.left + (data.clientX || 0), rect.top + (data.clientY || 0));
        }
    } else if (data.type === 'pc-computed' && data.id === selectedPcId && data.computed) {
        setStageComputedStyle(data.computed);
    } else if (data.type === 'pc-inline-start') {
        cancelStageFocusTimer();
    } else if (data.type === 'pc-inline-input' && data.id) {
        const nextHtml = HtmlAst.setText(projectFiles.html, data.id, data.text);
        applyHtmlTransform(nextHtml, data.id, { skipStageRender: true, coalesceHistory: true });
    } else if (data.type === 'pc-inline-edit' && data.id) {
        const nextHtml = HtmlAst.setText(projectFiles.html, data.id, data.text);
        applyHtmlTransform(nextHtml, data.id, { skipStageRender: true, coalesceHistory: true });
    } else if (data.type === 'pc-move-up' && data.id) {
        moveSelectedElement('up', data.id);
    } else if (data.type === 'pc-move-down' && data.id) {
        moveSelectedElement('down', data.id);
    } else if (data.type === 'pc-move-to' && data.sourceId && data.targetId) {
        const res = HtmlAst.moveElement(projectFiles.html, data.sourceId, data.targetId, data.position);
        if (res.moved) {
            applyHtmlTransform(res.html, res.newId);
            showNotice('Reordered element');
        }
    } else if (data.type === 'pc-duplicate' && data.id) {
        duplicateSelectedElement(data.id);
    } else if (data.type === 'pc-delete' && data.id) {
        deleteSelectedElement();
    } else if (data.type === 'pc-undo') {
        performUndo();
    } else if (data.type === 'pc-redo') {
        performRedo();
    } else if (data.type === 'pc-navigate' && typeof data.href === 'string') {
        followProjectLink(data.href);
    } else if (data.type === 'pc-follow-link' && data.id) {
        followSelectedLink(data.id);
    } else if (data.type === 'pc-console') {
        addConsoleEntry(data);
    }
});
